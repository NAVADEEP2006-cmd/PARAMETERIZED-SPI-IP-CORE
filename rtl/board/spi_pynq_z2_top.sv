// -----------------------------------------------------------------------------
// spi_pynq_z2_top.sv  -  Dedicated Hardware Demonstration Top for TUL PYNQ-Z2
//
// Target Board:       TUL PYNQ-Z2 (AMD Zynq-7020 xc7z020clg400-1)
// Target Connectors:  Pmod B (Header JB) & Onboard User I/O
//
// Architectural Role:
//   This module is a physical demonstration wrapper for the Parameterized SPI IP Core.
//   It bridges the physical FPGA pins (125 MHz Ethernet PHY clock, pushbuttons,
//   switches, LEDs, and Pmod B SPI pins) to the reusable 'spi_master_top' core.
//
// Clock Architecture:
//   - Physical Reference Clock: 125.0 MHz single-ended clock on pin H16 (Bank 35)
//     sourced from the onboard Realtek RTL8211E-VL Gigabit Ethernet PHY (U5, pin 46 CLK125).
//   - PHY Reset Dependency: PHYRSTB must be deasserted (held high / inactive) for the
//     PHY's internal clock generator to operate and supply the 125 MHz CLK125 signal.
//   - Core Operating Frequency: Operates synchronously on the 125 MHz reference clock.
//   - SCLK Generation: With CLOCK_DIVIDER = 15, SCLK = 125 MHz / (2 * 15) = 4.167 MHz.
//     This is a conservative initial operating target pending physical measurement (< 5 MHz recommended for unshielded Pmod headers).
//   - PS Clock Separation: The 50 MHz clock is a separate clock domain generated by the
//     Zynq Processing System (PS FCLK_CLK0) via an AXI-to-SPI bridge in production designs.
//     No MMCM or Clocking Wizard IP is instantiated in this standalone RTL baseline.
//
// Pin Allocation Summary:
//   - Clock & Reset:
//       sysclk       -> H16 (125 MHz PL reference clock, Bank 35, LVCMOS33)
//       reset_btn    -> D19 (Pushbutton BTN0, Bank 35, LVCMOS33, active-high)
//       start_btn    -> D20 (Pushbutton BTN1, Bank 35, LVCMOS33, active-high)
//   - Transaction Controls:
//       sw_slave_sel -> M20 (SW0), M19 (SW1) (Bank 35, LVCMOS33)
//   - SPI Bus on Pmod B (Bank 34, LVCMOS33, 8mA SLOW):
//       pad_cs_n[0]  -> W14 (Pin 1, JB1_P)
//       pad_mosi     -> Y14 (Pin 2, JB1_N)
//       pad_miso     -> T11 (Pin 3, JB2_P, internal PULLUP)
//       pad_sclk     -> T10 (Pin 4, JB2_N)
//       pad_cs_n[1]  -> V16 (Pin 7, JB3_P)
//       pad_cs_n[2]  -> W16 (Pin 8, JB3_N)
//       pad_cs_n[3]  -> V12 (Pin 9, JB4_P)
//   - Status LEDs:
//       led_busy     -> R14 (LD0, Bank 34, LVCMOS33)
//       led_done     -> P14 (LD1, Bank 34, LVCMOS33)
//       led_error    -> N16 (LD2, Bank 35, LVCMOS33)
//       led_active   -> M14 (LD3 - Transfer Active Indicator, Bank 35, LVCMOS33)
// -----------------------------------------------------------------------------

module spi_pynq_z2_top
  import spi_pkg::*;
#(
  parameter int DATA_WIDTH          = 8,
  parameter int CLOCK_DIVIDER       = 15, // 125 MHz / (2 * 15) = 4.167 MHz SCLK
  parameter int SPI_MODE            = 0,
  parameter int NUM_SLAVES          = 4,
  parameter bit LSB_FIRST           = 1'b0,
  parameter int DEBOUNCE_LIMIT      = 1_250_000, // ~10 ms at 125 MHz (override in TB)
  parameter int DONE_STRETCH_CYCLES = 12_500_000, // ~100 ms at 125 MHz (override in TB)
  parameter int ERR_STRETCH_CYCLES  = 31_250_000  // ~250 ms at 125 MHz (override in TB)
)(
  // Physical Board Clock & User Controls
  input  logic                      sysclk,         // 125 MHz PL Reference Clock (H16)
  input  logic                      reset_btn,      // BTN0 (D19) - Active-high reset
  input  logic                      start_btn,      // BTN1 (D20) - Trigger transaction
  input  logic [1:0]                sw_slave_sel,   // SW[1:0] (M20, M19) - Slave selection

  // Physical SPI Master I/O on Pmod B (Header JB)
  output logic                      pad_sclk,       // Pmod B Pin 4 (T10)
  output logic                      pad_mosi,       // Pmod B Pin 2 (Y14)
  input  logic                      pad_miso,       // Pmod B Pin 3 (T11)
  output logic [NUM_SLAVES-1:0]     pad_cs_n,       // Pmod B Pins 1, 7, 8, 9

  // Diagnostic Status LEDs
  output logic                      led_busy,       // LD0 (R14) - Core Busy
  output logic                      led_done,       // LD1 (P14) - Transfer Complete
  output logic                      led_error,      // LD2 (N16) - Transaction / Select Error
  output logic                      led_active      // LD3 (M14) - Transfer Active Indicator
);

  // ---------------------------------------------------------------------------
  // 1. Synchronizers and Edge Detectors for Pushbuttons
  // ---------------------------------------------------------------------------
  // Reliable startup and reset synchronization:
  // rst_sync initializes to 2'b00. In FPGA fabric (e.g. Zynq-7000 GSR), registers
  // power up to 0 unless initialized otherwise.
  // Active-high reset_btn (BTN0) is synchronized through a 2-stage flip-flop chain
  // to prevent metastability, asserting core_reset synchronously to sysclk.
  logic [1:0] rst_sync = 2'b00;
  logic       core_reset;

  always_ff @(posedge sysclk) begin
    rst_sync <= {rst_sync[0], reset_btn};
  end
  assign core_reset = rst_sync[1];

  // Start pushbutton (BTN1) synchronizer, debouncer, and single-pulse detector:
  // Physical pushbuttons bounce for multiple milliseconds. The debouncer ensures
  // that start_debounced only transitions when start_sync[1] remains stable for
  // DEBOUNCE_LIMIT consecutive clock cycles (~10 ms at 125 MHz).
  // A single-cycle start_pulse is generated on the rising edge of start_debounced,
  // guaranteeing exactly one transaction trigger per physical press.
  logic [1:0]  start_sync;
  logic        start_debounced;
  logic        start_debounced_d;
  logic        start_pulse;
  logic [23:0] debounce_cnt;

  always_ff @(posedge sysclk) begin
    if (core_reset) begin
      start_sync        <= 2'b00;
      start_debounced   <= 1'b0;
      start_debounced_d <= 1'b0;
      start_pulse       <= 1'b0;
      debounce_cnt      <= 24'd0;
    end else begin
      // 2-stage metastability synchronizer
      start_sync <= {start_sync[0], start_btn};

      // Debounce filter
      if (start_sync[1] != start_debounced) begin
        if (debounce_cnt >= 24'(DEBOUNCE_LIMIT)) begin
          start_debounced <= start_sync[1];
          debounce_cnt    <= 24'd0;
        end else begin
          debounce_cnt <= debounce_cnt + 24'd1;
        end
      end else begin
        debounce_cnt <= 24'd0;
      end

      // Single-cycle pulse on rising edge of debounced button state
      start_debounced_d <= start_debounced;
      start_pulse       <= start_debounced & ~start_debounced_d;
    end
  end

  // Synchronize slave select switch inputs
  logic [1:0] sw_sync_0, sw_sync_1;
  always_ff @(posedge sysclk) begin
    sw_sync_0 <= sw_slave_sel;
    sw_sync_1 <= sw_sync_0;
  end

  // ---------------------------------------------------------------------------
  // 2. Demonstration Transaction Generator
  // ---------------------------------------------------------------------------
  // Increments an 8-bit test pattern each time start_btn is pressed
  logic [DATA_WIDTH-1:0] tx_data_reg;
  /* verilator lint_off UNUSEDSIGNAL */
  logic [DATA_WIDTH-1:0] rx_data_wire;
  /* verilator lint_on UNUSEDSIGNAL */
  logic                  core_start;
  logic                  core_busy;
  logic                  core_done;
  logic                  core_error;
  logic                  core_select_error;
  logic                  core_transfer_active;

  always_ff @(posedge sysclk) begin
    if (core_reset) begin
      tx_data_reg <= 8'hA5; // Default recognizable initial test payload
      core_start  <= 1'b0;
    end else begin
      core_start  <= 1'b0;
      if (start_pulse && !core_busy) begin
        core_start  <= 1'b1;
        tx_data_reg <= tx_data_reg + 8'h01;
      end
    end
  end

  // ---------------------------------------------------------------------------
  // 3. Reusable Parameterized SPI Master Core Instantiation
  // ---------------------------------------------------------------------------
  spi_master_top #(
    .DATA_WIDTH       (DATA_WIDTH),
    .CLOCK_DIVIDER    (CLOCK_DIVIDER),
    .SPI_MODE         (SPI_MODE),
    .NUM_SLAVES       (NUM_SLAVES),
    .MISO_SYNC_STAGES (2),
    .ENABLE_PERF      (1'b0), // Omit perf counters for minimum board resource footprint
    .LSB_FIRST        (LSB_FIRST)
  ) u_spi_master (
    .clk              (sysclk),
    .reset            (core_reset),
    .start            (core_start),
    .tx_data          (tx_data_reg),
    .slave_select     (sw_sync_1[spi_idx_w(NUM_SLAVES)-1:0]),
    .rx_data          (rx_data_wire),
    .busy             (core_busy),
    .done             (core_done),
    .error            (core_error),
    .select_error     (core_select_error),
    .transfer_active  (core_transfer_active),
    .sclk             (pad_sclk),
    .mosi             (pad_mosi),
    .miso             (pad_miso),
    .cs_n             (pad_cs_n),
    .perf_clear       (1'b0),
    .perf_txn_count   (),
    .perf_bits_total  (),
    .perf_busy_cycles (),
    .perf_total_cycles(),
    .perf_last_latency(),
    .perf_last_sclk_cycles(),
    .perf_reject_count()
  );

  // ---------------------------------------------------------------------------
  // 4. Output Status LED Drive & Activity Pulse Extension
  // ---------------------------------------------------------------------------
  // Pulse-stretch 'done' and 'error' so brief events are clearly visible to human eye
  logic [27:0] done_stretch_cnt;
  logic        done_led_reg;
  logic [27:0] err_stretch_cnt;
  logic        err_led_reg;

  always_ff @(posedge sysclk) begin
    if (core_reset) begin
      done_stretch_cnt <= 28'd0;
      done_led_reg     <= 1'b0;
      err_stretch_cnt  <= 28'd0;
      err_led_reg      <= 1'b0;
    end else begin
      // Done stretch: ~100 ms at 125 MHz (12,500,000 cycles default)
      if (core_done) begin
        done_stretch_cnt <= 28'(DONE_STRETCH_CYCLES);
        done_led_reg     <= 1'b1;
      end else if (done_stretch_cnt > 28'd0) begin
        done_stretch_cnt <= done_stretch_cnt - 28'd1;
      end else begin
        done_led_reg     <= 1'b0;
      end

      // Error stretch: ~250 ms at 125 MHz (31,250,000 cycles default)
      if (core_error || core_select_error) begin
        err_stretch_cnt <= 28'(ERR_STRETCH_CYCLES);
        err_led_reg     <= 1'b1;
      end else if (err_stretch_cnt > 28'd0) begin
        err_stretch_cnt <= err_stretch_cnt - 28'd1;
      end else begin
        err_led_reg     <= 1'b0;
      end
    end
  end

  assign led_busy   = core_busy;
  assign led_done   = done_led_reg;
  assign led_error  = err_led_reg;
  assign led_active = core_transfer_active;

endmodule
